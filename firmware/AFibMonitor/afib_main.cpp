// ---------------------------------------------------------------- settings
static const int   FS_RAW        = 250;    // sampling rate, Hz
static const int   FS            = 125;    // model rate, Hz
static const int   WIN           = 1250;   // 10 s window
static const int   STRIDE        = 250;    // new prediction every 2 s
static const float AFIB_THRESHOLD = 0.5f;
static const float FLAT_STD_MV   = 0.01f;  // window std below this = electrodes off
static const int   ARENA_SIZE    = 80 * 1024;
static const uint32_t USB_TIMEOUT_MS = 1500;

// ---------------------------------------------------------------- filter
// butter(2, [0.5, 40], 'band', fs=250, output='sos'): b0 b1 b2 a1 a2
static const float SOS[2][5] = {
  {0.1424442454f, 0.2848884908f, 0.1424442454f, -0.6856000535f, 0.2606960323f},
  {1.0000000000f, -2.0000000000f, 1.0000000000f, -1.9822347504f, 0.9823948463f},
};
struct Biquad { float z1 = 0, z2 = 0; };
static Biquad bq[2];

static float filterSample(float x) {
  for (int s = 0; s < 2; s++) {           // transposed direct form II
    const float* c = SOS[s];
    float y = c[0] * x + bq[s].z1;
    bq[s].z1 = c[1] * x - c[3] * y + bq[s].z2;
    bq[s].z2 = c[2] * x - c[4] * y;
    x = y;
  }
  return x;
}
static void resetFilter() { memset(bq, 0, sizeof(bq)); }

// ---------------------------------------------------------------- buffers
static float ring[WIN];                    // last 10 s at 125 Hz (filtered, mV)
static volatile int ringHead = 0;          // next write position
static volatile int filled = 0;            // valid samples in ring
static volatile int sinceLast = 0;         // new samples since the last prediction
static volatile bool decimToggle = false;
static portMUX_TYPE ringMux = portMUX_INITIALIZER_UNLOCKED;

// display sweep (receives every 125 Hz sample)
static QueueHandle_t plotQueue;
static QueueHandle_t rawQueue;            // raw 250 Hz mV for "E 1" recording (bench test: SNR, live ECG figure)
static volatile bool rawStream = false;
static volatile uint32_t rawDropped = 0;   // samples lost because the queue was full (reported on "E 0")

static volatile uint32_t rawCount = 0;     // raw samples since the last reset

// ---------------------------------------------------------------- R-peak detector
// Exactly the same algorithm as detect_r() in the Kaggle notebook:
// derivative^2 -> 150 ms moving average -> adaptive threshold (35 % of a peak
// tracker that halves every 2 s) -> 250 ms refractory period.
static const int   N_RR     = 32;          // RR intervals per model input (RR model)
static const int   RR_EVERY = 4;           // new RR prediction every 4 beats
static const int   MA_N     = 19;          // 150 ms at 125 Hz
static const float R_THR    = 0.35f;
static const int   R_REFR   = 31;          // 250 ms
static const int   R_WARM   = 250;         // 2 s warm-up
static float rDecay = 0.99723f;            // set in setup(): 0.5^(1/(2*FS))

struct RDetector {
  float buf[MA_N]; float sum; float prev; float pk;
  int32_t i; int32_t last; bool armed;
};
static RDetector rd;
static float rrBuf[N_RR];                  // last RR intervals, seconds (ring)
static volatile int rrHead = 0, rrCount = 0, beatsSince = 0;
static volatile int32_t lastBeatI = -1;    // 125-Hz index of the last beat

static void resetDetector() {
  memset(&rd, 0, sizeof(rd));
  rd.last = -1000000; rd.armed = true;
  rrHead = 0; rrCount = 0; beatsSince = 0; lastBeatI = -1;
}

static void detectorStep(float x) {        // called for every 125-Hz sample (inside ringMux)
  float d = x - rd.prev; rd.prev = x;
  float e = d * d;
  int k = rd.i % MA_N;
  rd.sum += e - rd.buf[k]; rd.buf[k] = e;
  float env = rd.sum / MA_N;
  rd.pk = max(rd.pk * rDecay, env);
  if (rd.i >= R_WARM) {
    if (rd.armed && env > R_THR * rd.pk && rd.i - rd.last > R_REFR) {
      if (lastBeatI >= 0) {
        rrBuf[rrHead] = (rd.i - lastBeatI) / (float)FS;
        rrHead = (rrHead + 1) % N_RR;
        if (rrCount < N_RR) rrCount++;
        beatsSince++;
      }
      lastBeatI = rd.i; rd.last = rd.i; rd.armed = false;
    } else if (!rd.armed && env < 0.5f * R_THR * rd.pk) {
      rd.armed = true;
    }
  }
  rd.i++;
}

// ---------------------------------------------------------------- 30-second check
static const int CHK_N = 30 * FS;          // 3750 samples at 125 Hz
static float chkBuf[CHK_N];
static volatile int chkN = 0;
static volatile bool chkActive = false;
static uint32_t chkShownMs = 0;            // when the last verdict was drawn (kept on screen for 10 s)
static uint32_t chkFirstIrrMs = 0;         // "irregular" is shown only after two irregular checks within 10 min

static void pushRaw(float mv) {            // called at 250 Hz from either source
  rawCount++;
  if (rawStream && xQueueSend(rawQueue, &mv, 0) != pdTRUE) rawDropped++;
  float y = filterSample(mv);
  decimToggle = !decimToggle;
  if (!decimToggle) return;                // keep every 2nd sample -> 125 Hz
  portENTER_CRITICAL(&ringMux);
  ring[ringHead] = y;
  ringHead = (ringHead + 1) % WIN;
  if (filled < WIN) filled++;
  sinceLast++;
  detectorStep(y);
  if (chkActive && chkN < CHK_N) chkBuf[chkN++] = y;
  portEXIT_CRITICAL(&ringMux);
  xQueueSend(plotQueue, &y, 0);
}

static void resetWindow() {
  portENTER_CRITICAL(&ringMux);
  ringHead = 0; filled = 0; sinceLast = 0; rawCount = 0; decimToggle = false;
  resetDetector();
  portEXIT_CRITICAL(&ringMux);
  resetFilter();
}

// ---------------------------------------------------------------- sources
static volatile uint32_t lastUsbSampleMs = 0;
static bool usbMode() { return millis() - lastUsbSampleMs < USB_TIMEOUT_MS; }

static void adcTask(void*) {               // core 0, 250 Hz
  TickType_t last = xTaskGetTickCount();
  const TickType_t period = pdMS_TO_TICKS(1000 / FS_RAW);   // 4 ms
  for (;;) {
    vTaskDelayUntil(&last, period);
    if (usbMode()) continue;               // PC is streaming, ignore the ADC
    float mv = (float)analogReadMilliVolts(PIN_ECG);
    pushRaw(mv);
  }
}

static bool leadsOff() {
  if (PIN_LO_PLUS < 0 || PIN_LO_MINUS < 0 || usbMode()) return false;
  return digitalRead(PIN_LO_PLUS) || digitalRead(PIN_LO_MINUS);
}

// ---------------------------------------------------------------- model
static const tflite::Model* model = nullptr;
static tflite::MicroInterpreter* interpreter = nullptr;
static uint8_t* arena = nullptr;
static TfLiteTensor* inT = nullptr;
static TfLiteTensor* outT = nullptr;
static tflite::MicroMutableOpResolver<14> resolver;

static bool setupModel() {
  model = tflite::GetModel(afib_model);
  if (model->version() != TFLITE_SCHEMA_VERSION) {
    Serial.printf("Model schema %lu != %d\n", (unsigned long)model->version(), TFLITE_SCHEMA_VERSION);
    return false;
  }
  resolver.AddAdd();
  resolver.AddBatchToSpaceNd();
  resolver.AddConv2D();
  resolver.AddExpandDims();
  resolver.AddFullyConnected();
  resolver.AddLogistic();
  resolver.AddMaxPool2D();
  resolver.AddMean();
  resolver.AddPad();
  resolver.AddReshape();
  resolver.AddSpaceToBatchNd();
  resolver.AddQuantize();
  resolver.AddDequantize();
  resolver.AddRelu();

  arena = (uint8_t*)heap_caps_malloc(ARENA_SIZE, MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT);
  if (!arena) { Serial.println("Arena alloc failed"); return false; }
  static tflite::MicroInterpreter interp(model, resolver, arena, ARENA_SIZE);
  interpreter = &interp;
  if (interpreter->AllocateTensors() != kTfLiteOk) { Serial.println("AllocateTensors failed"); return false; }
  inT = interpreter->input(0);
  outT = interpreter->output(0);
  Serial.printf("Model %u B, arena used %u B, input type %d, dims %d\n",
                afib_model_len, (unsigned)interpreter->arena_used_bytes(), inT->type, inT->dims->size);
  return true;
}

struct Prediction {
  float prob = 0;       // AFib probability 0..1
  float bpm = 0;
  float stdMv = 0;
  uint32_t inferUs = 0;
  uint32_t spanRaw = 0; // raw (250 Hz) samples covered by the model input
  bool flat = false;
  bool valid = false;
};

// The firmware supports both models from the notebook; the type is read from the input shape:
//   RAW: [1, 1250, 1] — 10 s of z-scored ECG
//   RR : [1, 32, 2]   — 32 RR intervals, channels (RR-0.8)/0.25 and (RR/mean-1)/0.15
static bool rrModel = false;

static void detectModelKind() {
  rrModel = (inT->dims->size == 3 && inT->dims->data[1] == N_RR && inT->dims->data[2] == 2);
  Serial.printf("Model input [%d,%d,%d] -> %s model\n", inT->dims->data[0], inT->dims->data[1],
                inT->dims->size > 2 ? inT->dims->data[2] : 1, rrModel ? "RR" : "RAW");
}

static float window[WIN];                  // ordered copy of the ring
static float rrCopy[N_RR];

static void copyWindow() {
  portENTER_CRITICAL(&ringMux);
  int h = ringHead;
  for (int i = 0; i < WIN; i++) window[i] = ring[(h + i) % WIN];
  sinceLast = 0;
  int rh = rrHead;
  for (int i = 0; i < N_RR; i++) rrCopy[i] = rrBuf[(rh + i) % N_RR];   // oldest -> newest
  beatsSince = 0;
  portEXIT_CRITICAL(&ringMux);
}

static int8_t quant(float v) {
  int q = (int)lroundf(v / inT->params.scale) + inT->params.zero_point;
  return (int8_t)constrain(q, -128, 127);
}

static bool readyForPrediction() {
  if (rrModel) return rrCount >= N_RR && beatsSince >= RR_EVERY;
  return filled >= WIN && sinceLast >= STRIDE;
}

static bool noRecentBeats() {              // no heartbeat for 3 s -> electrodes off / no signal
  return filled >= WIN && (lastBeatI < 0 || rd.i - lastBeatI > 3 * FS);
}

static Prediction runModel() {
  Prediction p;
  copyWindow();
  double sum = 0, sq = 0;
  for (int i = 0; i < WIN; i++) { sum += window[i]; sq += (double)window[i] * window[i]; }
  float mean = sum / WIN;
  float sd = sqrt(max(0.0, sq / WIN - (double)mean * mean));
  p.stdMv = sd;
  if (filled >= WIN && sd < FLAT_STD_MV) { p.flat = true; return p; }

  if (rrModel) {
    float m = 0, span = 0;
    for (int i = 0; i < N_RR; i++) { rrCopy[i] = constrain(rrCopy[i], 0.2f, 2.0f); m += rrCopy[i]; span += rrCopy[i]; }
    m /= N_RR;
    for (int i = 0; i < N_RR; i++) {
      float f0 = (rrCopy[i] - 0.8f) / 0.25f, f1 = (rrCopy[i] / m - 1.0f) / 0.15f;
      if (inT->type == kTfLiteInt8) { inT->data.int8[2 * i] = quant(f0); inT->data.int8[2 * i + 1] = quant(f1); }
      else { inT->data.f[2 * i] = f0; inT->data.f[2 * i + 1] = f1; }
    }
    float m8 = 0;
    for (int i = N_RR - 8; i < N_RR; i++) m8 += rrCopy[i];
    p.bpm = 60.0f * 8 / m8;
    p.spanRaw = (uint32_t)(span * FS_RAW);
  } else {
    for (int i = 0; i < WIN; i++) window[i] = (window[i] - mean) / sd;   // z-score, as in training
    for (int i = 0; i < WIN; i++) {
      if (inT->type == kTfLiteInt8) inT->data.int8[i] = quant(window[i]);
      else inT->data.f[i] = window[i];
    }
    float m8 = 0; int n = 0;                 // heart rate from the detector's RR buffer
    for (int i = N_RR - 8; i < N_RR; i++) if (rrCopy[i] > 0) { m8 += rrCopy[i]; n++; }
    p.bpm = n ? 60.0f * n / m8 : 0;
    p.spanRaw = WIN * 2;
  }

  uint32_t t0 = micros();
  TfLiteStatus st = interpreter->Invoke();
  p.inferUs = micros() - t0;
  if (st != kTfLiteOk) { Serial.println("Invoke failed"); return p; }

  if (outT->type == kTfLiteInt8)
    p.prob = (outT->data.int8[0] - outT->params.zero_point) * outT->params.scale;
  else
    p.prob = outT->data.f[0];
  p.prob = constrain(p.prob, 0.0f, 1.0f);
  p.valid = true;
  return p;
}


// ---------------------------------------------------------------- BLE
// GATT service "AFib Monitor":
//  STATUS (read+notify), 13 bytes, little-endian:
//   u8 version(=1) | u8 state | u16 prob*1000 | u16 bpm*10 | u32 t_ms | u16 infer_us | u8 battery %
//   state: 0 = collecting, 1 = normal, 2 = AFib, 3 = check electrodes
//  ECG (notify), 46 bytes: u16 seq | f32 scale | 20 x i16 filtered ECG at 125 Hz (value = i16 * scale, mV)
#define AFIB_SERVICE_UUID "8f1e0001-4b6a-4c5e-9a0b-3a1f2e7d0001"
#define AFIB_STATUS_UUID  "8f1e0002-4b6a-4c5e-9a0b-3a1f2e7d0001"
#define AFIB_ECG_UUID     "8f1e0003-4b6a-4c5e-9a0b-3a1f2e7d0001"
static const int ECG_PER_PACKET = 20;
static BLECharacteristic* bleStatus = nullptr;
static BLECharacteristic* bleEcg = nullptr;
static float ecgPacket[ECG_PER_PACKET];
static int ecgN = 0;
static uint16_t ecgSeq = 0;
static volatile bool bleConnected = false;

class ServerCb : public BLEServerCallbacks {
  void onConnect(BLEServer*) override { bleConnected = true; }
  void onDisconnect(BLEServer* s) override { bleConnected = false; s->getAdvertising()->start(); }
};

static void setupBle() {
  BLEDevice::init("AFib-Monitor");
  BLEDevice::setMTU(185);                  // 46-byte ECG packets need MTU > 23
  BLEServer* server = BLEDevice::createServer();
  server->setCallbacks(new ServerCb());
  BLEService* svc = server->createService(AFIB_SERVICE_UUID);
  bleStatus = svc->createCharacteristic(AFIB_STATUS_UUID,
                BLECharacteristic::PROPERTY_READ | BLECharacteristic::PROPERTY_NOTIFY);
  bleStatus->addDescriptor(new BLE2902());
  bleEcg = svc->createCharacteristic(AFIB_ECG_UUID, BLECharacteristic::PROPERTY_NOTIFY);
  bleEcg->addDescriptor(new BLE2902());
  svc->start();
  BLEAdvertising* adv = BLEDevice::getAdvertising();
  adv->addServiceUUID(AFIB_SERVICE_UUID);
  adv->setScanResponse(true);
  BLEDevice::startAdvertising();
}

static void bleSend(uint8_t state, float prob, float bpm, uint32_t inferUs) {
  if (!bleStatus) return;
  uint8_t b[13];
  uint16_t p = (uint16_t)constrain(lroundf(prob * 1000), 0, 1000);
  uint16_t h = (uint16_t)constrain(lroundf(bpm * 10), 0, 65535);
  uint32_t t = millis();
  uint16_t us = (uint16_t)min<uint32_t>(inferUs, 65535);
  b[0] = 1; b[1] = state;
  memcpy(b + 2, &p, 2); memcpy(b + 4, &h, 2); memcpy(b + 6, &t, 4); memcpy(b + 10, &us, 2);
  int bat = boardBattery();
  b[12] = (uint8_t)constrain(bat, 0, 100);
  bleStatus->setValue(b, sizeof b);
  if (bleConnected) bleStatus->notify();
}

static void bleEcgSample(float mv) {     // called for every 125-Hz sample shown on screen
  if (!bleEcg || !bleConnected) { ecgN = 0; return; }
  ecgPacket[ecgN++] = mv;
  if (ecgN == ECG_PER_PACKET) {
    float mx = 1e-6f;
    for (int i = 0; i < ECG_PER_PACKET; i++) mx = max(mx, fabsf(ecgPacket[i]));
    float scale = mx / 32000.0f;
    uint8_t b[6 + 2 * ECG_PER_PACKET];
    memcpy(b, &ecgSeq, 2); memcpy(b + 2, &scale, 4);
    for (int i = 0; i < ECG_PER_PACKET; i++) {
      int16_t q = (int16_t)lroundf(ecgPacket[i] / scale);
      memcpy(b + 6 + 2 * i, &q, 2);
    }
    bleEcg->setValue(b, sizeof b);
    bleEcg->notify();
    ecgSeq++; ecgN = 0;
  }
}

static uint8_t stateOf(const Prediction& p, bool leadOff) {
  if (leadOff || p.flat) return 3;
  if (!p.valid) return 0;
  return p.prob >= AFIB_THRESHOLD ? 2 : 1;
}

// ---------------------------------------------------------------- display
static const int W = 320, H = 240;
static const int PLOT_Y = 34, PLOT_H = 120;
static int sweepX = 0, lastPy = -1;
static float plotMin = -1, plotMax = 1, runMin = 1e9, runMax = -1e9;
#if HAS_DISPLAY
static const uint16_t COL_BG = TFT_BLACK, COL_GRID = 0x18E3, COL_ECG = 0x07E0;
#endif

static void drawGridColumn(int x) {
#if HAS_DISPLAY
  M5.Display.drawFastVLine(x, PLOT_Y, PLOT_H, (x % 25 == 0) ? COL_GRID : COL_BG);
  if (x % 25 != 0) for (int y = PLOT_Y; y < PLOT_Y + PLOT_H; y += 25) M5.Display.drawPixel(x, y, COL_GRID);
#else
  (void)0;
#endif
}

static void plotSample(float v) {
#if HAS_DISPLAY
  // auto-scale every sweep
  runMin = min(runMin, v); runMax = max(runMax, v);
  float range = max(plotMax - plotMin, 0.05f);
  int py = PLOT_Y + PLOT_H - 4 - (int)((v - plotMin) / range * (PLOT_H - 8));
  py = constrain(py, PLOT_Y, PLOT_Y + PLOT_H - 1);
  for (int k = 1; k <= 6; k++) drawGridColumn((sweepX + k) % W);   // erase ahead
  if (lastPy >= 0 && sweepX > 0) M5.Display.drawLine(sweepX - 1, lastPy, sweepX, py, COL_ECG);
  lastPy = py;
  sweepX++;
  if (sweepX >= W) {
    sweepX = 0; lastPy = -1;
    if (runMax > runMin) { plotMin = runMin; plotMax = runMax; }
    runMin = 1e9; runMax = -1e9;
  }
#else
  (void)v;
#endif
}

