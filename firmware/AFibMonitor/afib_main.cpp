#include <Arduino.h>
/*
 * AFib Monitor — M5Stack CoreS3 SE + AD8232
 * Ultra-Low-Power Atrial Fibrillation Detection via Quantized TCN on Microcontrollers
 * Author: Bektur Asilov
 *
 * Pipeline (same as the training notebook):
 *   ADC 250 Hz -> band-pass 0.5–40 Hz (Butterworth, 2 biquads) -> /2 -> 125 Hz
 *   -> 10-s window (1250 samples) -> z-score -> int8 TCN (TFLite Micro) -> AFib probability
 *
 * Signal sources:
 *   1) AD8232 on G10 (default)
 *   2) USB serial: a PC streams MIT-BIH samples ("D <mV>" lines at 250 Hz), see afib_stream.py
 *
 * Serial commands (115200 baud):
 *   D <mV>   one raw sample (250 Hz) from the PC; switches the source to USB
 *   B        benchmark: 100 inferences, prints mean/min/max time and arena size
 *   R        reset the window buffer
 *   I        info (model size, arena, ops)
 *   C        "check me in 30 s": record 30 s, then print the verdict (also started by tapping the status bar)
 *
 * Board: "M5CoreS3" (esp32 core 3.x). Libraries: M5Unified, M5GFX.
 * Our own patch (hardware/patch_v1, no screen): board "ESP32S3 Dev Module" and -DBOARD_PATCH_V1, see board.h;
 * the 30-s check then starts from the button and the verdict goes to Serial and the phone.
 * TFLite Micro comes bundled with the esp32 core (esp-tflite-micro).
 */

