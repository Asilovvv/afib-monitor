"""backend/app/pvc_model.json -> firmware/AFibMonitor/pvc_model.h (tree tables for ectopy::tree_score).
    python tools/pvc_export.py [model.json] [out.h]"""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "backend"))
from app.ectopy import THRESHOLD   # decision threshold lives with the server code (Notebook 14)
src = sys.argv[1] if len(sys.argv) > 1 else "backend/app/pvc_model.json"
dst = sys.argv[2] if len(sys.argv) > 2 else "firmware/AFibMonitor/pvc_model.h"
m = json.load(open(src))
assert m["kind"] == "trees", "only tree models are exported to the device"
starts, rows = [], []
for t in m["trees"]:
    starts.append(len(rows))
    rows += t
lines = ["// Generated by tools/pvc_export.py from backend/app/pvc_model.json - do not edit.", "#pragma once",
         '#include "ectopy.h"', f"static const int PVC_N_TREES = {len(m['trees'])};",
         f"static const double PVC_BASELINE = {m['baseline']!r};", f"static const double PVC_THRESHOLD = {THRESHOLD!r};",
         "static const int PVC_TREE_START[] = {" + ", ".join(map(str, starts)) + "};",
         "static const ectopy::Node PVC_NODES[] = {"]
lines += [f"  {{{int(f)}, {float(th)!r}, {int(l)}, {int(r)}, {float(v)!r}, {int(leaf)}}}," for f, th, l, r, v, leaf in rows]
lines.append("};")
open(dst, "w").write("\n".join(lines) + "\n")
print(dst, len(m["trees"]), "trees", len(rows), "nodes")
